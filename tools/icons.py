"""Generate fonts-src/icons.txt: 1-bit weather icons centred on a 25x25 grid.

Sun and cloud are traced from the original Homezone; the rest are cleaned-up
1-bit versions of its rain, snow, storm and fog."""

import sys

W = H = 25

SUN = """
............#............
...........###...........
...........###...........
....#......###......#....
...###.....###.....###...
....###....###....###....
.....###.........###.....
......###..###..###......
.........#######.........
........#########........
........#########........
.#####.###########.#####.
######.###########.######
.#####.###########.#####.
........#########........
........#########........
.........#######.........
......###..###..###......
.....###.........###.....
....###....###....###....
...###.....###.....###...
....#......###......#....
...........###...........
...........###...........
............#............
"""

CLOUD = """
............#####.....
..........#########...
.........###########..
....#################.
..###################.
..####################
.#####################
######################
######################
######################
######################
######################
######################
######################
######################
######################
######################
.####################.
.####################.
...################...
"""


def art(s):
    return [r for r in s.strip("\n").split("\n")]


def blank():
    return [[0] * W for _ in range(H)]


def stamp(g, a, dx, dy, v=1):
    for y, row in enumerate(art(a) if isinstance(a, str) else a):
        for x, c in enumerate(row):
            if c == "#" and 0 <= y + dy < H and 0 <= x + dx < W:
                g[y + dy][x + dx] = v


def centered(a, top=None):
    """Art centred horizontally in the grid, vertically on the grid's centre row."""
    rows = art(a) if isinstance(a, str) else a
    h, w = len(rows), max(len(r) for r in rows)
    g = blank()
    stamp(g, rows, (W - w + 1) // 2, (H - h + 1) // 2 if top is None else top)
    return g


def small_cloud():
    c = art(CLOUD)
    return c[:7] + c[7:10] + c[17:]  # drop 7 of the 10 straight rows


def rows_from_spans(spans, w):
    return [
        "".join("#" if any(a <= x <= b for a, b in sp) else "." for x in range(w))
        for sp in spans
    ]


def icon_sun():
    return centered(SUN)


def icon_cloud():
    return centered(CLOUD, top=3)  # even height: centre on row 12.5


def icon_fog():
    bar = [".###################.", "#####################", ".###################."]
    blank_rows = ["." * 21] * 4
    return centered(bar + blank_rows + bar + blank_rows + bar)


def icon_rain():
    c = small_cloud()
    drops = []
    for r in range(9):
        o = 2 - r // 3
        drops.append([(x0 + o, x0 + o + 2) for x0 in (2, 8, 14)])
    return centered(c + ["." * 22] + rows_from_spans(drops, 22))


def icon_snow():
    arm = [
        [(10, 10)],
        [(9, 11)],
        [(9, 11)],
        [(9, 11)],
        [(9, 11)],
        [(9, 11)],
        [(1, 1), (9, 11), (19, 19)],
        [(0, 3), (9, 11), (17, 20)],
        [(0, 5), (9, 11), (15, 20)],
        [(2, 7), (9, 11), (13, 18)],
        [(4, 16)],
        [(5, 15)],
    ]
    return centered(rows_from_spans(arm + [[(7, 13)]] + arm[::-1], 21))


def icon_storm():
    up = [
        [(9, 9)],
        [(8, 10)],
        [(7, 9)],
        [(7, 9)],
        [(6, 8)],
        [(6, 8)],
        [(5, 7)],
        [(5, 7)],
        [(4, 6)],
        [(4, 6)],
        [(3, 5)],
        [(2, 4)],
    ]
    bar = [[(2, 8)], [(1, 9)], [(2, 8)]]
    down = [
        [(5, 7)],
        [(5, 7)],
        [(4, 6)],
        [(4, 6)],
        [(3, 5)],
        [(3, 5)],
        [(2, 4)],
        [(2, 4)],
        [(1, 3)],
        [(1, 1)],
    ]
    return centered(rows_from_spans(up[1:] + bar + down, 11))


# Same set and mapping as the original (WMO code -> icon in src/pkjs/index.js).
ICONS = [
    ("a", "clear", icon_sun),
    ("c", "cloudy", icon_cloud),
    ("d", "rain", icon_rain),
    ("e", "snow", icon_snow),
    ("f", "storm", icon_storm),
    ("g", "fog", icon_fog),
]

out = [
    "# Weather icons, 25x25. Generated by tools/icons.py; do not edit.",
    "size 25",
    "advance 25",
    "left 0",
    "",
]
for ch, name, fn in ICONS:
    out.append(f"char {ch}  # {name}")
    out += ["".join("#" if v else "." for v in row) for row in fn()]
    out.append("")
open(sys.argv[1], "w").write("\n".join(out))
