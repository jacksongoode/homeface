"""Write src/embeddedjs/metrics.js from the font atlases the Alloy build generates, so text can be
placed by its visible ink instead of its advance box.

Poco blends 4-bit glyph alpha into the 2-bit-per-channel display, where the faintest
anti-aliased columns (alpha below MIN_ALPHA/15) round away to the background, so they don't count
as ink. MIN_ALPHA was measured on emulator screenshots of both themes.

Run after `pebble build` whenever a font or its character set changes, then build again.
"""

import glob
import json
import struct

from PIL import Image

FONTS = {"time": "SpaceGrotesk-SemiBold-72", "num": "SpaceGrotesk-SemiBold-22", "icons": "Pix-icons-25"}
MIN_ALPHA = 5


def glyphs(fnt):
    """{char: (x, y, w, h, xoffset, xadvance)} from a binary BMFont v3 file."""
    data = open(fnt, "rb").read()
    assert data[:4] == b"BMF\x03", fnt
    out, i = {}, 4
    while i < len(data):
        kind, size = data[i], struct.unpack_from("<I", data, i + 1)[0]
        if kind == 4:  # chars block, 20 bytes per glyph
            for k in range(i + 5, i + 5 + size, 20):
                cid, x, y, w, h, xo, _, xa, _, _ = struct.unpack_from("<IHHHHhhhBB", data, k)
                out[chr(cid)] = (x, y, w, h, xo, xa)
        i += 5 + size
    return out


def metrics(base):
    atlas = Image.open(base + ".png").getchannel("A")
    out = {}
    for ch, (x, y, w, h, xo, xa) in glyphs(base + ".fnt").items():
        alpha = [max(atlas.getpixel((x + c, y + r)) >> 4 for r in range(h)) for c in range(w)]
        cols = [c for c, a in enumerate(alpha) if a >= MIN_ALPHA]
        out[ch] = [xo + cols[0], cols[-1] - cols[0] + 1, xa] if cols else [0, 0, xa]
    return out


result = {}
for name, stem in FONTS.items():
    found = glob.glob(f"build/mods/emery/**/files/{stem}.fnt", recursive=True)
    assert found, f"{stem}.fnt not found; run `pebble build` first"
    result[name] = metrics(found[0][: -len(".fnt")])

body = json.dumps(result, ensure_ascii=False, separators=(",", ":"))
open("src/embeddedjs/metrics.js", "w").write(
    "// Generated by tools/metrics.py; do not edit.\n"
    "// {char: [left bearing, ink width, advance]}\n"
    f"export default {body};\n"
)
