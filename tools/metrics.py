"""Write src/c/metrics.auto.h: per-glyph ink metrics as the SDK rasterizes them, so text can be
placed by its ink instead of its advance box. Rerun after changing a font or its character set."""

import freetype as ft

FONTS = [  # C name, ttf, pixel size, characters
    ("TIME", "resources/fonts/SpaceGrotesk-SemiBold.ttf", 72, "0123456789"),
    ("NUM", "resources/fonts/SpaceGrotesk-SemiBold.ttf", 22, "-0123456789:%,.K\xb0CF"),
    ("ICONS", "resources/fonts/Pix-icons.ttf", 25, "acdefg"),
]
FLAGS = ft.FT_LOAD_RENDER | ft.FT_LOAD_MONOCHROME | ft.FT_LOAD_TARGET_MONO

out = [
    "// Generated by tools/metrics.py; do not edit.",
    "// {left bearing, ink width, advance}",
]
for name, path, size, chars in FONTS:
    face = ft.Face(path)
    face.set_pixel_sizes(0, size)
    rows = []
    for ch in chars:
        face.load_char(ch, FLAGS)
        g = face.glyph
        rows.append(f"{{{g.bitmap_left}, {g.bitmap.width}, {g.advance.x // 64}}}")
    cstr = "".join(
        c if c != "\xb0" else '\\xB0" "' for c in chars
    )  # end the hex escape
    out.append(
        f'static const FontMetrics s_m_{name.lower()} = {{"{cstr}", {{{", ".join(rows)}}}}};'
    )
open("src/c/metrics.auto.h", "w").write("\n".join(out) + "\n")
